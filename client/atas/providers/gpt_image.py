"""Strict gpt-image-2 image generation for identity references and stills.

It deliberately has no model fallback: character reference assets must either
be generated by gpt-image-2 or fail with an actionable configuration error.
"""

from __future__ import annotations

import base64
import mimetypes
import os
import time
import uuid
from collections.abc import Sequence
from pathlib import Path
from typing import Any


class GPTImage2Unavailable(RuntimeError):
    """Raised when the required gpt-image-2 backend is not configured."""


def _image_base_url() -> str:
    explicit = os.environ.get("AVWM_IMAGE_BASE_URL", "").strip()
    if explicit:
        base = explicit.rstrip("/")
        return base if base.endswith("/v1") else f"{base}/v1"
    responses = os.environ.get("ATAS_LLM_URL", "").strip().rstrip("/")
    if responses:
        if responses.endswith("/responses"):
            responses = responses[: -len("/responses")]
        return responses if responses.endswith("/v1") else f"{responses}/v1"
    fallback = os.environ.get("OPENAI_BASE_URL", "").strip()
    if fallback:
        base = fallback.rstrip("/")
        return base if base.endswith("/v1") else f"{base}/v1"
    return "https://api.openai.com/v1"


def _image_stream_enabled() -> bool:
    raw = os.environ.get("AVWM_IMAGE_STREAM")
    if raw is None or not raw.strip():
        return False
    return raw.strip() == "1"


class GPTImage2Generator:
    MODEL = "gpt-image-2"

    def __init__(self, settings: Any) -> None:
        image = settings.image
        self.api_key = (
            os.environ.get("AVWM_IMAGE_API_KEY", "").strip()
            or os.environ.get("ATAS_LLM_API_KEY", "").strip()
            or os.environ.get("OPENAI_API_KEY", "").strip()
        )
        self.base_url = _image_base_url()
        self.retries = max(
            1,
            int(os.environ.get("AVWM_IMAGE_RETRIES", str(image.retries))),
        )
        self.size = os.environ.get("AVWM_IMAGE_SIZE", "1536x1024").replace("*", "x")
        self.quality = os.environ.get("AVWM_IMAGE_QUALITY", "high").strip().lower()
        if self.quality not in {"low", "medium", "high", "auto"}:
            raise GPTImage2Unavailable(
                "AVWM_IMAGE_QUALITY must be low, medium, high, or auto"
            )
        if image.model != self.MODEL:
            raise GPTImage2Unavailable(
                "character assets require image model gpt-image-2; "
                f"configured model {image.model!r} is forbidden"
            )
        if not self.api_key:
            raise GPTImage2Unavailable(
                "gpt-image-2 is unavailable: set AVWM_IMAGE_API_KEY, "
                "OPENAI_API_KEY, or ATAS_LLM_API_KEY"
            )
        try:
            from openai import OpenAI
        except ImportError as exc:
            raise GPTImage2Unavailable(
                "gpt-image-2 is unavailable: install the openai Python package"
            ) from exc
        self._client_type = OpenAI

    def _client(self) -> Any:
        # A fresh client prevents Cloudflare from pinning retries to the same
        # overloaded origin through a reused keep-alive connection.
        return self._client_type(
            api_key=self.api_key,
            base_url=self.base_url,
            max_retries=0,
        )

    @staticmethod
    def _response_b64(response: Any, *, stream: bool) -> str | None:
        if not stream:
            data = getattr(response, "data", None) or []
            return getattr(data[0], "b64_json", None) if data else None
        result: str | None = None
        for event in response:
            candidate = getattr(event, "b64_json", None)
            if candidate:
                result = candidate
            if getattr(event, "type", "") in {
                "image_edit.completed",
                "image_generation.completed",
            }:
                break
        return result

    def generate(
        self,
        prompt: str,
        output: Path,
        *,
        references: Sequence[Path] = (),
        negative_prompt: str = "",
        seed: int = 0,
    ) -> None:
        del seed  # gpt-image-2 does not expose a deterministic seed contract.
        output.parent.mkdir(parents=True, exist_ok=True)
        full_prompt = prompt
        if negative_prompt:
            full_prompt += f"\n严格避免：{negative_prompt}"
        last_error: Exception | None = None
        print(f"gpt-image-2 start {output.name}", flush=True)
        for attempt in range(self.retries):
            try:
                stream = _image_stream_enabled()
                kwargs: dict[str, Any] = {
                    "model": self.MODEL,
                    "prompt": full_prompt,
                    "size": self.size,
                    "n": 1,
                    "extra_headers": {
                        "X-Client-Request-Id": uuid.uuid4().hex,
                        "Connection": "close",
                    },
                }
                if stream:
                    kwargs.update(
                        stream=True,
                        partial_images=0,
                        quality=self.quality,
                        output_format="png",
                    )
                paths = tuple(Path(path) for path in references)
                client = self._client()
                if paths:
                    files = [
                        (
                            path.name or f"reference_{index}.png",
                            path.read_bytes(),
                            mimetypes.guess_type(path.name)[0] or "image/png",
                        )
                        for index, path in enumerate(paths)
                    ]
                    kwargs["image"] = files[0] if len(files) == 1 else files
                    response = client.images.edit(**kwargs)
                else:
                    response = client.images.generate(**kwargs)
                b64 = self._response_b64(response, stream=stream)
                if not b64:
                    raise RuntimeError("gpt-image-2 response did not contain b64_json")
                output.write_bytes(base64.b64decode(b64))
                if output.stat().st_size == 0:
                    raise RuntimeError("gpt-image-2 wrote an empty image")
                return
            except Exception as exc:  # provider transient errors are retryable
                last_error = exc
                if attempt + 1 < self.retries:
                    response = getattr(exc, "response", None)
                    retry_after = None
                    if response is not None:
                        retry_after = response.headers.get("retry-after")
                    try:
                        wait_s = float(retry_after) if retry_after else 0.0
                    except (TypeError, ValueError):
                        wait_s = 0.0
                    time.sleep(max(wait_s, min(30.0, 2.0 * (attempt + 1))))
        raise RuntimeError(
            f"gpt-image-2 failed after {self.retries} attempts: {last_error}"
        ) from last_error
